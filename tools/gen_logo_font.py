#!/usr/bin/env python3
"""从 font_data.js 提取「墨屏日报」32px 宋体点阵，生成 C 数组头文件给固件用。"""
import base64, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "cloudflare", "font_data.js")
OUT = os.path.join(ROOT, "firmware-src", "src", "logo_font.h")

TEXT = "墨屏日报"

src = open(FONT, encoding="utf-8").read()
# 提取 GLYPH_CJK 对象文本段
m = re.search(r"const GLYPH_CJK = \{(.*?)\n\};", src, re.S)
if not m:
    sys.exit("GLYPH_CJK not found")
pairs = re.findall(r'"((?:\\u[0-9a-fA-F]{4}|[^"\\]))"\s*:\s*"([A-Za-z0-9+/=]+)"', m.group(1))
table = {}
for esc, b64 in pairs:
    ch = esc.encode().decode("unicode_escape") if esc.startswith("\\u") else esc
    table[ch] = b64

FONT_W = FONT_H = 32
lines = []
lines.append("// AUTO-GENERATED by tools/gen_logo_font.py — 墨屏日报 32px 宋体点阵（源自 font_data.js）")
lines.append("#ifndef LOGO_FONT_H_")
lines.append("#define LOGO_FONT_H_")
lines.append("#include <pgmspace.h>")
lines.append("#define LOGO_FONT_W 32")
lines.append("#define LOGO_FONT_H 32")
lines.append("#define LOGO_FONT_BYTES 128  // 32 rows * 4 bytes")
lines.append("")
for ch in TEXT:
    b64 = table.get(ch)
    if not b64:
        sys.exit(f"glyph missing: {ch}")
    raw = base64.b64decode(b64)
    assert len(raw) == 128, f"{ch}: {len(raw)} bytes"
    hexs = ",".join(f"0x{b:02X}" for b in raw)
    lines.append(f"// U+{ord(ch):04X} {ch}")
    lines.append(f"static const uint8_t GM_{ord(ch):04X}[LOGO_FONT_BYTES] PROGMEM = {{{hexs}}};")
lines.append("")
# 指针表：按 TEXT 顺序
ptrs = ",".join(f"GM_{ord(c):04X}" for c in TEXT)
lines.append(f"static const uint8_t* const LOGO_GLYPHS[{len(TEXT)}] = {{{ptrs}}};")
lines.append(f"#define LOGO_TEXT_LEN {len(TEXT)}")
lines.append("#endif")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"OK -> {OUT}: {len(TEXT)} glyphs")
